"""Real SDK acceptance for the published FormatTool; no third-party test packages."""
import argparse
import hashlib
import json
import pathlib
import subprocess
import tempfile
import unittest


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


class FormattingAcceptance(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.area = tempfile.TemporaryDirectory(prefix="format-accept-", dir=ARGS.work)
        cls.root = pathlib.Path(cls.area.name)
        cls.project = cls.root / "App"
        cls.project.mkdir()
        (cls.project / "Nested").mkdir()
        (cls.project / "App.csproj").write_text(
            '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework>'
            '</PropertyGroup><ItemGroup><Compile Remove="Excluded.cs" /></ItemGroup></Project>', encoding="utf-8")
        (cls.project / ".editorconfig").write_text(
            'root = true\n[*.cs]\nindent_style = space\nindent_size = 4\nend_of_line = lf\n'
            'csharp_preserve_single_line_blocks = false\ncsharp_preserve_single_line_statements = false\n', encoding="utf-8")
        (cls.project / "Nested" / ".editorconfig").write_text('[*.cs]\nindent_size = 2\n', encoding="utf-8")
        (cls.project / "Unselected.cs").write_text('class UserEdit{int Value=  7;} // preserve my edit\n', encoding="utf-8")
        (cls.project / "Excluded.cs").write_text('class Excluded{}\n', encoding="utf-8")
        (cls.project / "Generated.g.cs").write_text('// <auto-generated/>\nclass Generated{int Value=  7;}\n', encoding="utf-8")
        cls.chosen = cls.project / "Nested" / "Chosen.cs"
        cls.chosen.write_text('class Chosen{\nvoid Run(){\nint value=1;\n}\n}\n', encoding="utf-8")
        restore = subprocess.run(['dotnet', 'restore', str(cls.project / 'App.csproj'), '--source', str(cls.root)],
                                 capture_output=True, text=True, timeout=120)
        if restore.returncode:
            raise RuntimeError(restore.stdout + restore.stderr)

    @classmethod
    def tearDownClass(cls):
        cls.area.cleanup()

    def invoke(self, **overrides):
        request = dict(schemaVersion=1, workspace="App/App.csproj", files=["Nested/Chosen.cs"],
                       mode="whitespace", action="check", allowRestore=False)
        request.update(overrides)
        path = self.root / "request.json"
        path.write_text(json.dumps(request), encoding="utf-8")
        command = [str(ARGS.tool)]
        if ARGS.tool.suffix == '.dll':
            command.insert(0, 'dotnet')
        # Deliberately invoke from the parent, the historical silent-no-match case.
        run = subprocess.run(command + ['--request', str(path)], cwd=self.root,
                             capture_output=True, text=True, encoding="utf-8", timeout=180)
        result = json.loads(run.stdout)
        self.assertEqual(run.stderr, '', run.stderr)
        return run.returncode, result

    def test_whitespace_editorconfig_and_actual_scope(self):
        self.chosen.write_text('class Chosen{\nvoid Run(){\nint value=1;\n}\n}\n', encoding="utf-8")
        before = {path: digest(path) for path in self.project.rglob('*.cs')}
        code, result = self.invoke()
        self.assertEqual(code, 2, result)
        self.assertEqual(result['status'], 'changes-required')
        self.assertEqual(result['changedFiles'], [])
        self.assertEqual(before, {path: digest(path) for path in before})
        self.assertTrue(result['findings'])
        code, result = self.invoke(action="apply")
        self.assertEqual(code, 0, result)
        self.assertEqual(result['status'], 'applied')
        self.assertEqual(result['changedFiles'], [str(self.chosen)])
        self.assertIn('\n  void Run()\n  {\n    int value = 1;', self.chosen.read_text())
        self.assertEqual(result['remainingFindings'], [])
        for path, original in before.items():
            if path != self.chosen:
                self.assertEqual(digest(path), original)
        code, result = self.invoke()
        self.assertEqual((code, result['status']), (0, 'clean'))

    def test_invalid_empty_and_unmatched_selection(self):
        for files, expected in [([], 'invalid-request'), (['Missing.cs'], 'invalid-selection'),
                                (['Nested'], 'invalid-selection'), (['Excluded.cs'], 'unmatched-selection')]:
            with self.subTest(files=files):
                code, result = self.invoke(files=files)
                self.assertEqual(code, 1, result)
                self.assertEqual(result['errorCode'], expected)
                self.assertEqual(result['changedFiles'], [])

    def test_missing_and_unloadable_project(self):
        code, result = self.invoke(workspace="App/Missing.csproj")
        self.assertEqual((code, result['errorCode']), (1, 'load-failed'))
        broken = self.project / 'Broken.csproj'
        broken.write_text('<Project><Invalid', encoding='utf-8')
        code, result = self.invoke(workspace="App/Broken.csproj")
        self.assertEqual((code, result['errorCode']), (1, 'load-failed'))
        broken.unlink()

    def test_apply_load_failure_reports_actual_state(self):
        project_file = self.project / 'App.csproj'
        original = project_file.read_text()
        before = digest(self.chosen)
        try:
            project_file.write_text(original.replace('</Project>',
                '<Target Name="RejectDesignTime" BeforeTargets="Compile" Condition="\'$(DesignTimeBuild)\' == \'true\'">'
                '<Error Text="Deliberate design-time load failure" /></Target></Project>'), encoding='utf-8')
            code, result = self.invoke(action='apply')
            self.assertEqual((code, result['status'], result['errorCode']), (1, 'failed', 'load-failed'))
            self.assertEqual(digest(self.chosen), before)
            self.assertEqual(result['changedFiles'], [])
        finally:
            project_file.write_text(original, encoding='utf-8')

    def test_generated_exclusion_and_solution_selection(self):
        generated = self.project / 'Generated.g.cs'
        before = digest(generated)
        solution = self.root / 'Sample.slnx'
        solution.write_text('<Solution><Project Path="App/App.csproj" /></Solution>', encoding='utf-8')
        code, result = self.invoke(workspace='Sample.slnx', files=['App/Generated.g.cs'], action='apply')
        self.assertEqual((code, result['status']), (0, 'clean'), result)
        self.assertEqual(digest(generated), before)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--tool', required=True, type=pathlib.Path)
    parser.add_argument('--work', required=True, type=pathlib.Path)
    ARGS, rest = parser.parse_known_args()
    ARGS.tool = ARGS.tool.resolve()
    ARGS.work.mkdir(parents=True, exist_ok=True)
    unittest.main(argv=[__file__] + rest, verbosity=2)
