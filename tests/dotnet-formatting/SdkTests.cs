    [FormatSdkFact]
    public void DesignTimeFailureReportsObservedSourceChanges()
    {
        using var fixture = new FormatFixture();
        byte[] before = null!;
        (int Exit, JsonElement Result) refused = default;
        (int Exit, JsonElement Result) changed = default;

        this.Given(GivenADesignTimeTargetThatFailsBeforeWriting, "a design time target that fails before writing")
            .When(WhenApplyingWithTheFailingTarget, "applying with the failing target")
            .Then(ThenReportFailureWithoutSourceChanges, "report failure without source changes")
            .Given(GivenADesignTimeTargetThatWritesBeforeFailing, "a design time target that writes before failing")
            .When(WhenApplyingWithTheWritingTarget, "applying with the writing target")
            .Then(ThenReportTheObservedSourceChange, "report the observed source change")
            .BDDfy();

        async Task GivenADesignTimeTargetThatFailsBeforeWriting()
        {
            await fixture.Restore();
            fixture.WriteProject("""
                <Target Name="RejectDesignTime" BeforeTargets="Compile" Condition="'$(DesignTimeBuild)' == 'true'">
                  <Error Text="Deliberate design-time load failure" />
                </Target>
                """);
            before = File.ReadAllBytes(fixture.Chosen);
        }

        async Task WhenApplyingWithTheFailingTarget()
        {
            refused = await fixture.Invoke(action: "apply");
        }

        void ThenReportFailureWithoutSourceChanges()
        {
            Failure(refused, "load-failed");
            Assert.Equal(before, File.ReadAllBytes(fixture.Chosen));
            Assert.Empty(Items(refused.Result, "changedFiles"));
            Assert.Contains(Items(refused.Result, "commands"),
                row => row.GetProperty("exitCode").GetInt32() != 0 && !string.IsNullOrEmpty(Text(row, "standardOutput")));
        }

        void GivenADesignTimeTargetThatWritesBeforeFailing() => fixture.WriteProject("""
            <Target Name="WriteThenFail" BeforeTargets="Compile" Condition="'$(DesignTimeBuild)' == 'true'">
              <WriteLinesToFile File="Nested/Chosen.cs" Lines="class Chosen {}" Overwrite="true" />
              <Error Text="Deliberate failure after a source side effect" />
            </Target>
            """);

        async Task WhenApplyingWithTheWritingTarget()
        {
            changed = await fixture.Invoke(action: "apply");
        }

        void ThenReportTheObservedSourceChange()
        {
            Failure(changed, "load-failed");
            Assert.Equal(fixture.Chosen, Assert.Single(Items(changed.Result, "changedFiles")).GetString());
            Assert.NotEqual(Original, File.ReadAllText(fixture.Chosen));
        }
    }

    [FormatSdkFact]
    public void SlnxAndEditorConfigGeneratedSelectionsAreUnreportedAndUnchanged()
    {
        using var fixture = new FormatFixture();
        const string generated = "// <auto-generated/>\nclass Generated{int Value=  7;}\n";
        const string marked = "class Marked{int value=  1;}\n";
        Dictionary<string, byte[]> generatedSources = null!;
        (int Exit, JsonElement Result) slnx = default;
        (int Exit, JsonElement Result) classic = default;

        this.Given(GivenARestoredSlnxWithTwoKindsOfGeneratedSource, "a restored slnx with two kinds of generated source")
            .When(WhenApplyingToTheGeneratedFiles, "applying to the generated files")
            .Then(ThenLeaveBothGeneratedFilesUnreportedAndUnchanged, "leave both generated files unreported and unchanged")
            .Given(GivenTheEquivalentClassicSolution, "the equivalent classic solution")
            .When(WhenCheckingAuthoredSourceThroughTheClassicSolution, "checking authored source through the classic solution")
            .Then(ThenReportRequiredChanges, "report required changes")
            .BDDfy();

        async Task GivenARestoredSlnxWithTwoKindsOfGeneratedSource()
        {
            var markedPath = fixture.Write("App/Marked.cs", marked);
            File.AppendAllText(Path.Combine(fixture.Root, "App", ".editorconfig"), "\n[Marked.cs]\ngenerated_code = true\n");
            var generatedPath = fixture.Write("App/Generated.g.cs", generated);
            fixture.Write("Sample.slnx", Solution);
            await fixture.Restore();
            generatedSources = new()
            {
                [generatedPath] = File.ReadAllBytes(generatedPath),
                [markedPath] = File.ReadAllBytes(markedPath)
            };
        }

        async Task WhenApplyingToTheGeneratedFiles() =>
            slnx = await fixture.Invoke(workspace: "Sample.slnx", files: ["App/Generated.g.cs", "App/Marked.cs"], action: "apply");

        void ThenLeaveBothGeneratedFilesUnreportedAndUnchanged()
        {
            Outcome(slnx, 0, "clean");
            Assert.Equal(generatedSources.Keys.Order(), Items(slnx.Result, "unreportedSelections").Select(row => row.GetString()).Order());
            Assert.Empty(Items(slnx.Result, "findings"));
            Assert.Empty(Items(slnx.Result, "changedFiles"));
            foreach (var (path, original) in generatedSources)
                Assert.Equal(original, File.ReadAllBytes(path));
        }

        void GivenTheEquivalentClassicSolution() => fixture.Write("Sample.sln", ClassicSolution);

        async Task WhenCheckingAuthoredSourceThroughTheClassicSolution() =>
            classic = await fixture.Invoke(workspace: "Sample.sln", files: ["App/Nested/Chosen.cs"]);

        void ThenReportRequiredChanges() => Outcome(classic, 2, "changes-required");
    }

    [FormatSdkFact(artifact: true, caseSensitive: true)]
    [Trait("Boundary", "CaseSensitiveArtifact")]
    public void CaseAliasOnCaseSensitiveVolumeIsRejectedBeforeFormatter()
    {
        using var fixture = new FormatFixture(CaseSensitiveRoot);
        const string upperText = "class Upper{int n=  1;}\n";
        const string lowerText = "class Lower{int n=  2;}\n";
        string upper = null!;
        string lower = null!;
        byte[] upperBefore = null!;
        byte[] lowerBefore = null!;
        (int Exit, JsonElement Result) run = default;

        this.Given(GivenDistinctCaseAliasesOnTheSelectedVolume, "distinct case aliases on the selected volume")
            .When(WhenApplyingToOneCaseAlias, "applying to one case alias")
            .Then(ThenRefuseBeforeFormattingAndPreserveBothFiles, "refuse before formatting and preserve both files")
            .BDDfy();

        async Task GivenDistinctCaseAliasesOnTheSelectedVolume()
        {
            Assert.True(Path.IsPathFullyQualified(CaseSensitiveRoot!), "Supply an absolute case-sensitive APFS fixture root.");

            upper = fixture.Write("App/CaseAlias.cs", upperText);
            Assert.False(File.Exists(Path.Combine(fixture.Root, "App", "casealias.cs")), "The selected volume must be case-sensitive.");
            lower = fixture.Write("App/casealias.cs", lowerText);
            fixture.WriteProject("""<ItemGroup><Compile Include="CaseAlias.cs;casealias.cs" /></ItemGroup>""", explicitCompile: true);
            await fixture.Restore();
            upperBefore = File.ReadAllBytes(upper);
            lowerBefore = File.ReadAllBytes(lower);
        }

        async Task WhenApplyingToOneCaseAlias()
        {
            run = await fixture.Invoke(files: ["CaseAlias.cs"], action: "apply", artifact: true);
        }

        void ThenRefuseBeforeFormattingAndPreserveBothFiles()
        {
            Failure(run, "unsupported-selection");
            Assert.DoesNotContain(Items(run.Result, "commands"), row =>
            {
                var arguments = Items(row, "arguments").Select(item => item.GetString()).ToArray();
                return arguments[0] == "format" && arguments.Contains("--include");
            });
            Assert.Equal(upperBefore, File.ReadAllBytes(upper));
            Assert.Equal(lowerBefore, File.ReadAllBytes(lower));
        }
    }

