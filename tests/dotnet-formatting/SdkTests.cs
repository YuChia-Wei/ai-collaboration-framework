    [FormatSdkFact(artifact: true)]
    [Trait("Boundary", "PublishedArtifact")]
    public async Task PublishedExecutableChecksAndAppliesNestedEditorConfigToSelectedBytesOnly()
    {
        using var fixture = new FormatFixture();
        fixture.Write("App/Generated.g.cs", "// <auto-generated/>\nclass Generated{int Value=  7;}\n");
        await fixture.Restore();
        var original = Directory.GetFiles(Path.Combine(fixture.Root, "App"), "*.cs", SearchOption.AllDirectories)
            .ToDictionary(path => path, File.ReadAllBytes);

        var compact = await fixture.Invoke(artifact: true);
        Outcome(compact, 2, "changes-required");
        Assert.Empty(Items(compact.Result, "changedFiles"));
        Assert.NotEmpty(Items(compact.Result, "findings"));
        Assert.Equal(SdkVersion, Text(compact.Result, "sdkVersion"));
        Assert.False(compact.Result.TryGetProperty("notes", out _));
        Assert.False(compact.Result.TryGetProperty("ruleCapabilities", out _));
        Assert.NotEmpty(Items(compact.Result, "commands"));
        Assert.All(Items(compact.Result, "commands"), row =>
        {
            Assert.False(row.TryGetProperty("standardOutput", out _));
            Assert.False(row.TryGetProperty("standardError", out _));
        });
        foreach (var (path, bytes) in original)
            Assert.Equal(bytes, File.ReadAllBytes(path));

        var verbose = await fixture.Invoke(artifact: true, verbose: true);
        Outcome(verbose, 2, "changes-required");
        Assert.Equal(compact.Result.GetProperty("findings").GetRawText(), verbose.Result.GetProperty("findings").GetRawText());
        Assert.Contains(Items(verbose.Result, "commands"), row => !string.IsNullOrEmpty(Text(row, "standardOutput")));
        Assert.NotEmpty(Items(verbose.Result, "ruleCapabilities"));
        Assert.NotEmpty(Items(verbose.Result, "notes"));
        foreach (var (path, bytes) in original)
            Assert.Equal(bytes, File.ReadAllBytes(path));

        var applied = await fixture.Invoke(artifact: true, action: "apply");
        Outcome(applied, 0, "applied");
        Assert.Equal(fixture.Chosen, Assert.Single(Items(applied.Result, "changedFiles")).GetString());
        Assert.Contains("\n  void Run()\n  {\n    int value = 1;", File.ReadAllText(fixture.Chosen));
        Assert.Empty(Items(applied.Result, "remainingFindings"));
        foreach (var (path, bytes) in original.Where(pair => pair.Key != fixture.Chosen))
            Assert.Equal(bytes, File.ReadAllBytes(path));

        var clean = await fixture.Invoke(artifact: true);
        Outcome(clean, 0, "clean");
        Assert.Equal(fixture.Chosen, Assert.Single(Items(clean.Result, "unreportedSelections")).GetString());
    }

