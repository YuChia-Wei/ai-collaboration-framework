using Aicf.Dotnet.TestSupport;
using System.Text.Json;
using static FormatTool.IntegrationTests.FormatFixture;

namespace FormatTool.IntegrationTests;

public sealed class PublishedFormatTests
{
    [FormatArtifactFact]
    [Trait("Boundary", "PublishedArtifact")]
    public void PublishedExecutableChecksAndAppliesNestedEditorConfigToSelectedBytesOnly()
    {
        var executable = FormatArtifactProfile.RequireExecutable();
        using var fixture = new FormatFixture();
        Dictionary<string, byte[]> original = null!;
        (int Exit, JsonElement Result) compact = default;
        (int Exit, JsonElement Result) verbose = default;
        (int Exit, JsonElement Result) applied = default;
        (int Exit, JsonElement Result) clean = default;

        this.Given(GivenRestoredSourcesAndNestedEditorConfig, "restored sources and nested editor config")
            .When(WhenCheckingWithCompactOutput, "checking with compact output")
            .Then(ThenReportFindingsWithoutWriting, "report findings without writing")
            .When(WhenCheckingWithVerboseOutput, "checking with verbose output")
            .Then(ThenReportTheSameFindingsWithCommandDetails, "report the same findings with command details")
            .When(WhenApplyingThePublishedFormatter, "applying the published formatter")
            .Then(ThenChangeOnlyTheSelectedSource, "change only the selected source")
            .When(WhenCheckingTheEditedSource, "checking the edited source")
            .Then(ThenReportNoRemainingChanges, "report no remaining changes")
            .BDDfy();

        async Task GivenRestoredSourcesAndNestedEditorConfig()
        {
            fixture.Write("App/Generated.g.cs", "// <auto-generated/>\nclass Generated{int Value=  7;}\n");
            await fixture.Restore();
            original = Directory.GetFiles(Path.Combine(fixture.Root, "App"), "*.cs", SearchOption.AllDirectories)
                .ToDictionary(path => path, File.ReadAllBytes);
        }

        async Task WhenCheckingWithCompactOutput()
        {
            compact = await fixture.Invoke(artifact: executable);
        }

        void ThenReportFindingsWithoutWriting()
        {
            Outcome(compact, 2, "changes-required");
            Assert.Empty(Items(compact.Result, "changedFiles"));
            Assert.NotEmpty(Items(compact.Result, "findings"));
            Assert.Equal(SdkVersion, Text(compact.Result, "sdkVersion"));
            Assert.False(compact.Result.TryGetProperty("notes", out _));
            Assert.False(compact.Result.TryGetProperty("ruleCapabilities", out _));
            Assert.NotEmpty(Items(compact.Result, "commands"));
            Assert.All(Items(compact.Result, "commands"), row =>
            {
                Assert.False(row.TryGetProperty("standardOutput", out _));
                Assert.False(row.TryGetProperty("standardError", out _));
            });
            foreach (var (path, bytes) in original)
                Assert.Equal(bytes, File.ReadAllBytes(path));
        }

        async Task WhenCheckingWithVerboseOutput()
        {
            verbose = await fixture.Invoke(artifact: executable, verbose: true);
        }

        void ThenReportTheSameFindingsWithCommandDetails()
        {
            Outcome(verbose, 2, "changes-required");
            Assert.True(JsonElement.DeepEquals(compact.Result.GetProperty("findings"), verbose.Result.GetProperty("findings")));
            Assert.Contains(Items(verbose.Result, "commands"), row => !string.IsNullOrEmpty(Text(row, "standardOutput")));
            Assert.NotEmpty(Items(verbose.Result, "ruleCapabilities"));
            Assert.NotEmpty(Items(verbose.Result, "notes"));
            foreach (var (path, bytes) in original)
                Assert.Equal(bytes, File.ReadAllBytes(path));
        }

        async Task WhenApplyingThePublishedFormatter()
        {
            applied = await fixture.Invoke(artifact: executable, action: "apply");
        }

        void ThenChangeOnlyTheSelectedSource()
        {
            Outcome(applied, 0, "applied");
            Assert.Equal(fixture.Chosen, Assert.Single(Items(applied.Result, "changedFiles")).GetString());
            Assert.Contains("\n  void Run()\n  {\n    int value = 1;", File.ReadAllText(fixture.Chosen));
            Assert.Empty(Items(applied.Result, "remainingFindings"));
            foreach (var (path, bytes) in original.Where(pair => pair.Key != fixture.Chosen))
                Assert.Equal(bytes, File.ReadAllBytes(path));
        }

        async Task WhenCheckingTheEditedSource()
        {
            clean = await fixture.Invoke(artifact: executable);
        }

        void ThenReportNoRemainingChanges()
        {
            Outcome(clean, 0, "clean");
            Assert.Equal(fixture.Chosen, Assert.Single(Items(clean.Result, "unreportedSelections")).GetString());
        }
    }

    [FormatArtifactFact(caseSensitive: true)]
    [Trait("Boundary", "CaseSensitiveArtifact")]
    public void CaseAliasOnCaseSensitiveVolumeIsRejectedBeforeFormatter()
    {
        var executable = FormatArtifactProfile.RequireExecutable();
        using var fixture = new FormatFixture(FormatArtifactProfile.RequireCaseRoot());
        const string upperText = "class Upper{int n=  1;}\n";
        const string lowerText = "class Lower{int n=  2;}\n";
        string upper = null!;
        string lower = null!;
        byte[] upperBefore = null!;
        byte[] lowerBefore = null!;
        (int Exit, JsonElement Result) run = default;

        this.Given(GivenDistinctCaseAliasesOnTheSelectedVolume, "distinct case aliases on the selected volume")
            .When(WhenApplyingToOneCaseAlias, "applying to one case alias")
            .Then(ThenRefuseBeforeFormattingAndPreserveBothFiles, "refuse before formatting and preserve both files")
            .BDDfy();

        async Task GivenDistinctCaseAliasesOnTheSelectedVolume()
        {
            upper = fixture.Write("App/CaseAlias.cs", upperText);
            Assert.False(File.Exists(Path.Combine(fixture.Root, "App", "casealias.cs")), "The selected volume must be case-sensitive.");
            lower = fixture.Write("App/casealias.cs", lowerText);
            fixture.WriteProject("""<ItemGroup><Compile Include="CaseAlias.cs;casealias.cs" /></ItemGroup>""", explicitCompile: true);
            await fixture.Restore();
            upperBefore = File.ReadAllBytes(upper);
            lowerBefore = File.ReadAllBytes(lower);
        }

        async Task WhenApplyingToOneCaseAlias()
        {
            run = await fixture.Invoke(files: ["CaseAlias.cs"], action: "apply", artifact: executable);
        }

        void ThenRefuseBeforeFormattingAndPreserveBothFiles()
        {
            Failure(run, "unsupported-selection");
            Assert.DoesNotContain(Items(run.Result, "commands"), row =>
            {
                var arguments = Items(row, "arguments").Select(item => item.GetString()).ToArray();
                return arguments[0] == "format" && arguments.Contains("--include");
            });
            Assert.Equal(upperBefore, File.ReadAllBytes(upper));
            Assert.Equal(lowerBefore, File.ReadAllBytes(lower));
        }
    }
}
